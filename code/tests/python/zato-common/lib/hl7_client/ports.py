# stdlib
import socket

# ################################################################################################################################
# ################################################################################################################################

def find_free_port() -> 'int':
    """ Returns a TCP port that is free at the moment of the call.
    """
    with socket.socket() as probe:
        probe.bind(('127.0.0.1', 0))
        out = probe.getsockname()[1]

    return out

