# stdlib
import logging
from importlib import import_module

# Zato
from zato.common.webapp.server import serve

# ################################################################################################################################
# ################################################################################################################################

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(name)s - %(levelname)s - %(message)s')

# ################################################################################################################################
# ################################################################################################################################

Env_Host = 'Zato_B2B_Console_Host'
Env_Port = 'Zato_B2B_Console_Port'

Default_Host = '0.0.0.0'
Default_Port = '8186'

_app_name = 'the B2B console'

_wsgi_module = 'zato.common.b2b.console.wsgi'

# ################################################################################################################################
# ################################################################################################################################

def main() -> 'None':
    """ The entry point - serves the console.
    """
    wsgi = import_module(_wsgi_module)

    serve(wsgi.application, _app_name, Env_Host, Env_Port, Default_Host, Default_Port)

# ################################################################################################################################
# ################################################################################################################################

if __name__ == '__main__':
    main()

